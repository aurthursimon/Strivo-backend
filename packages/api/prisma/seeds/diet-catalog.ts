function realSubstitutions(
  ingredientName: string,
  options: Array<{ name: string; amount: string }>,
) {
  return options
    .filter(
      (option) =>
        option.name.toLocaleLowerCase('pt-BR') !== ingredientName.toLocaleLowerCase('pt-BR'),
    )
    .slice(0, 5);
}

function i(name: string, amount: string, group: SubstitutionGroup) {
  return {
    name,
    amount,
    substitutions: realSubstitutions(name, SUBSTITUTIONS[group]),
  };
}

type DietRecipeDraft = Omit<DietRecipeSeed, 'steps'> & { steps?: string[] };

function ingredientName(
  recipe: Pick<DietRecipeSeed, 'ingredients'>,
  index: number,
  fallback: string,
) {
  return recipe.ingredients[index]?.name ?? fallback;
}

function steps(recipe: DietRecipeDraft): string[] {
  const name = recipe.name;
  const lowerName = name.toLowerCase();
  const main = ingredientName(recipe, 0, 'ingrediente principal');
  const second = ingredientName(recipe, 1, 'base');
  const third = ingredientName(recipe, 2, 'acompanhamento');

  if (/(smoothie|shake|vitamina)/.test(lowerName)) {
    return [
      `Separe ${main}, ${second} e ${third}; lave frutas e folhas antes de usar.`,
      'Bata tudo no liquidificador com agua, gelo ou a bebida indicada ate ficar cremoso.',
      'Ajuste a textura com mais liquido se necessario e sirva imediatamente.',
      'Para variar, troque um ingrediente por uma das substituicoes cadastradas mantendo a porcao.',
    ];
  }

  if (/(iogurte|kefir)/.test(lowerName)) {
    return [
      `Coloque ${main} em uma tigela ou pote individual.`,
      `Misture ${second} e finalize com ${third}, mantendo as porcoes indicadas.`,
      'Deixe gelar por alguns minutos se quiser uma textura mais firme.',
      'Use as substituicoes cadastradas para trocar fruta, sementes ou base lactea.',
    ];
  }

  if (/(mingau)/.test(lowerName)) {
    return [
      `Aqueca ${main} com ${second} em fogo baixo, mexendo ate engrossar.`,
      `Misture ${third} no final para manter textura e fibras.`,
      'Desligue o fogo quando estiver cremoso e ajuste canela ou cacau sem acucar se desejar.',
      'Sirva quente e troque fruta ou semente pelas substituicoes cadastradas.',
    ];
  }

  if (/(omelete|ovos|tofu mexido|shakshuka)/.test(lowerName)) {
    return [
      `Aqueca uma frigideira antiaderente e prepare ${main} em fogo medio.`,
      `Adicione ${second} e ${third}, mexendo ou dobrando conforme o prato pedir.`,
      'Cozinhe ate firmar, evitando excesso de oleo para manter as calorias previstas.',
      'Finalize com ervas, limao ou pimenta e use as substituicoes se quiser variar.',
    ];
  }

  if (/(tapioca|panqueca|cuscuz)/.test(lowerName)) {
    return [
      `Prepare ${main} em frigideira ou cuscuzeira ate ficar cozido e firme.`,
      `Adicione ${second} e ${third} como recheio ou acompanhamento.`,
      'Mantenha fogo medio para nao ressecar e respeite a quantidade cadastrada.',
      'Troque recheio ou base pelas substituicoes mantendo a porcao sugerida.',
    ];
  }

  if (/(sanduiche|wrap|rolinhos|tacos)/.test(lowerName)) {
    return [
      `Abra a base e distribua ${main} de forma uniforme.`,
      `Acrescente ${second} e ${third}, deixando a montagem firme para comer com facilidade.`,
      'Dobre, enrole ou feche o sanduiche e aqueca rapidamente se fizer sentido para o prato.',
      'Use as substituicoes cadastradas para variar proteina, base ou vegetais.',
    ];
  }

  if (/(mix|salada de frutas|fruta com)/.test(lowerName)) {
    return [
      `Porcione ${main} e ${second} em um pote ou tigela.`,
      `Acrescente ${third} para dar crocancia e melhorar a saciedade.`,
      'Misture apenas na hora de comer para preservar textura.',
      'Substitua frutas, sementes ou gorduras boas usando as opcoes cadastradas.',
    ];
  }

  if (/(homus|pate|guacamole|abacate)/.test(lowerName)) {
    return [
      `Amasse ou misture ${main} com ${second} ate formar uma pasta cremosa.`,
      `Sirva com ${third} ou use como recheio, respeitando a porcao indicada.`,
      'Tempere com limao, alho, ervas ou vinagre sem adicionar molhos caloricos.',
      'Troque a base, vegetal ou gordura boa por uma substituicao cadastrada.',
    ];
  }

  if (/(pudim|creme|gelatina|leite vegetal)/.test(lowerName)) {
    return [
      `Misture ${main} com ${second} ate incorporar bem.`,
      `Acrescente ${third} e leve para gelar quando o preparo pedir consistencia.`,
      'Sirva frio em porcao individual para facilitar o controle de calorias.',
      'Use as substituicoes cadastradas para variar base, fruta ou sementes.',
    ];
  }

  if (/(sopa|curry|chili|feijoada|moqueca|carne de panela)/.test(lowerName)) {
    return [
      `Refogue temperos com pouco oleo e adicione ${main}.`,
      `Inclua ${second} e ${third}, cubra parcialmente com agua ou caldo leve e cozinhe.`,
      'Mantenha fogo baixo ate os ingredientes ficarem macios e o caldo encorpar.',
      'Ajuste sal, limao e ervas no final; varie com as substituicoes cadastradas.',
    ];
  }

  if (/(lasanha|abobrinha recheada|bolinho|chips)/.test(lowerName)) {
    return [
      `Prepare ${main} e monte com ${second} e ${third} em forma ou assadeira.`,
      'Asse em temperatura media ate dourar e firmar a textura.',
      'Deixe descansar alguns minutos antes de servir para manter o formato.',
      'Troque recheio, vegetal ou complemento usando as substituicoes cadastradas.',
    ];
  }

  if (
    /(salmao|tilapia|sardinha|atum|camarao|bacalhau|tainha|berbigao|ostras|peixada|peixe)/.test(
      lowerName,
    )
  ) {
    return [
      `Tempere ${main} com limao, ervas e pouco sal.`,
      `Prepare ${second} e ${third} enquanto a proteina grelha, assa ou aquece rapidamente.`,
      'Cozinhe a proteina ate ficar no ponto, sem empanar ou fritar por imersao.',
      'Monte o prato e use substituicoes para variar peixe, base ou vegetal.',
    ];
  }

  if (
    /(frango|patinho|bife|carne|almondegas|lombo|pernil|marreco|charque|galeto|mortadela)/.test(
      lowerName,
    )
  ) {
    return [
      `Tempere ${main} com alho, limao, ervas e pouco sal.`,
      `Grelhe, asse ou cozinhe a proteina e prepare ${second} e ${third} em paralelo.`,
      'Monte o prato com a porcao cadastrada e evite molhos pesados.',
      'Troque proteina, carboidrato ou vegetal pelas substituicoes cadastradas.',
    ];
  }

  return [
    `Separe os ingredientes do ${name.toLowerCase()} e confira as porcoes cadastradas.`,
    `Prepare ${main}, ${second} e ${third} usando cozimento, grelha ou montagem simples.`,
    'Monte o prato na porcao sugerida e ajuste temperos leves no final.',
    'Use uma das substituicoes cadastradas para variar mantendo a mesma estrutura nutricional.',
  ];
}

function prepDetail(recipe: Pick<DietRecipeSeed, 'mealType' | 'name' | 'ingredients'>): string {
  const animalFoods = recipe.ingredients
    .map((ingredient) => ingredient.name)
    .join(' ')
    .toLowerCase();

  if (/(peito de frango|frango desfiado|frango moido|peito de peru|marreco)/.test(animalFoods)) {
    return 'Cozinhe frango e peru ate atingir 74 °C no centro; refrigere as sobras em ate duas horas.';
  }
  if (/(patinho moido|ovos|charque magro|mortadela)/.test(animalFoods)) {
    return 'Cozinhe carne moida e preparacoes com ovos ate atingir 71 °C no centro; em ovos simples, firme clara e gema.';
  }
  if (
    /(atum|tilapia|sardinha|camarao|salmao|pescada branca|linguado|bacalhau|tainha|berbigao|ostras)/.test(
      animalFoods,
    )
  ) {
    return 'Cozinhe peixes e frutos do mar ate 63 °C no centro ou ate a carne ficar opaca e separar facilmente.';
  }
  if (/(patinho em bife|carne de panela magra|lombo suino magro)/.test(animalFoods)) {
    return 'Cozinhe cortes inteiros de boi ou porco ate 63 °C no centro e deixe descansar por 3 minutos antes de servir.';
  }
  if (/(iogurte|queijo|ricota|kefir|whey)/.test(animalFoods)) {
    return 'Mantenha os laticinios refrigerados e nao deixe a preparacao fora da geladeira por mais de duas horas.';
  }
  if (recipe.mealType === 'BREAKFAST') {
    return 'Para agilizar a manha, deixe frutas lavadas e bases cozidas ou porcionadas na noite anterior.';
  }
  if (recipe.mealType === 'MORNING_SNACK' || recipe.mealType === 'AFTERNOON_SNACK') {
    return 'Leve em pote fechado e mantenha refrigerado quando houver laticinios, ovos, peixe ou frango.';
  }
  if (recipe.mealType === 'SUPPER') {
    return 'Mantenha a porcao leve e evite acrescentar acucar, mel ou granola fora do planejado.';
  }
  return 'Para marmita, resfrie antes de tampar e mantenha molho, folhas ou crocantes separados ate servir.';
}

function withPrepDetail(recipe: DietRecipeDraft, baseSteps: string[]): string[] {
  if (baseSteps.length >= 5) return baseSteps;
  return [...baseSteps, prepDetail(recipe)];
}

function r(recipe: DietRecipeDraft): DietRecipeSeed {
  const recipeSteps = recipe.steps ?? steps(recipe);
  const ingredients = recipe.ingredients.map((ingredient) => {
    if (ingredient.name !== 'Ovos') return ingredient;
    if (recipe.dietTypes.includes('VEGETARIAN')) {
      return {
        ...ingredient,
        substitutions: realSubstitutions(ingredient.name, VEGETARIAN_PROTEIN_SUBSTITUTIONS),
      };
    }
    if (recipe.dietTypes.includes('PESCATARIAN')) {
      return {
        ...ingredient,
        substitutions: realSubstitutions(ingredient.name, PESCATARIAN_PROTEIN_SUBSTITUTIONS),
      };
    }
    return ingredient;
  });
  return {
    ...recipe,
    ingredients,
    steps: withPrepDetail(recipe, recipeSteps),
  };
}

type RecipeNutrition = readonly [
  calories: number,
  protein: number,
  carbs: number,
  fat: number,
  prepTimeMin: number,
];
type RecipeIngredientInput = readonly [name: string, amount: string, group: SubstitutionGroup];

function catalogRecipe(
  name: string,
  mealType: MealType,
  nutrition: RecipeNutrition,
  dietTypes: string[],
  ingredients: RecipeIngredientInput[],
): DietRecipeSeed {
  const [calories, protein, carbs, fat, prepTimeMin] = nutrition;
  return r({
    name,
    mealType,
    calories,
    protein,
    carbs,
    fat,
    prepTimeMin,
    dietTypes,
    ingredients: ingredients.map(([ingredientName, amount, group]) =>
      i(ingredientName, amount, group),
    ),
  });
}

