type ExerciseKey = keyof typeof EXERCISES;

function defaultTempo(exercise: ExerciseSeed): string {
  if (exercise.category === 'CARDIO')
    return 'Ritmo continuo, com transicoes suaves de intensidade.';
  if (exercise.category === 'FLEXIBILITY' || exercise.category === 'RECOVERY') {
    return 'Movimentos lentos, 2 a 3 segundos por fase, sem dor.';
  }
  if (exercise.durationSec !== undefined && exercise.sets !== undefined) {
    return 'Sustente a posicao com controle e sem compensar a postura.';
  }
  return '2 segundos na fase de descida, pausa curta no controle e subida firme.';
}

function defaultTargetRpe(exercise: ExerciseSeed): string {
  if (exercise.category === 'CARDIO') return 'RPE 5-7, ainda conseguindo falar frases curtas.';
  if (exercise.difficulty === 'advanced') return 'RPE 8-9, mantendo tecnica limpa.';
  if (exercise.difficulty === 'intermediate') return 'RPE 7-8, com 2 a 3 repeticoes em reserva.';
  return 'RPE 6-7, com 3 a 4 repeticoes em reserva.';
}

function defaultProgression(exercise: ExerciseSeed): string {
  if (exercise.category === 'CARDIO') {
    return 'Aumente 1 a 2 minutos ou um nivel de resistencia quando terminar confortavel.';
  }
  if (exercise.category === 'FLEXIBILITY' || exercise.category === 'RECOVERY') {
    return 'Aumente a amplitude aos poucos, nunca forcando dor ou formigamento.';
  }
  if (exercise.reps?.includes('-')) {
    return 'Quando completar o topo da faixa em todas as series, aumente pouca carga na proxima sessao.';
  }
  return 'Progrida primeiro com mais controle tecnico; depois aumente carga ou tempo gradualmente.';
}

function defaultSafetyNotes(exercise: ExerciseSeed): string[] {
  const notes = ['Pare se houver dor aguda, tontura ou falta de ar fora do esperado.'];
  if (
    exercise.muscleGroups.some((group) =>
      ['quadriceps', 'gluteos', 'posterior', 'panturrilhas'].includes(group),
    )
  ) {
    notes.push('Mantenha joelhos alinhados aos pes e reduza amplitude se houver desconforto.');
  }
  if (exercise.muscleGroups.some((group) => ['peito', 'ombros', 'triceps'].includes(group))) {
    notes.push('Evite encolher os ombros e mantenha escapas estaveis.');
  }
  if (exercise.muscleGroups.some((group) => ['costas', 'core', 'lombar'].includes(group))) {
    notes.push('Preserve coluna neutra e abdomen ativo durante toda a serie.');
  }
  return notes.slice(0, 3);
}

function ex(key: ExerciseKey, override: Partial<ExerciseSeed> = {}): TemplateExerciseSeed {
  const base = EXERCISES[key] as ExerciseSeed;
  return {
    key,
    ...base,
    tempo: base.tempo ?? defaultTempo(base),
    targetRpe: base.targetRpe ?? defaultTargetRpe(base),
    progression: base.progression ?? defaultProgression(base),
    safetyNotes: base.safetyNotes ?? defaultSafetyNotes(base),
    ...override,
  };
}

function day(
  dayOfWeek: number,
  name: string,
  focusArea: string,
  estimatedMinutes: number,
  exercises: TemplateExerciseSeed[],
): WorkoutDaySeed {
  return { dayOfWeek, name, focusArea, estimatedMinutes, exercises };
}

function template(params: WorkoutTemplateSeed): WorkoutTemplateSeed {
  return params;
}

